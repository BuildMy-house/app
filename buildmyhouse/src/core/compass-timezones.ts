export const COMPASS_FALLBACK_ZONE = 'Etc/GMT'

const FALLBACK_DEGREES: [number, number] = ZONE_DEGREES[COMPASS_FALLBACK_ZONE] ?? [51.466667, 0]

export function compassDegreesForZone(zoneId: string): [number, number] {
  return ZONE_DEGREES[zoneId] ?? FALLBACK_DEGREES
}

/** OS IANA zone via Intl; null/undefined when the platform hides it. */
export function resolveTimezone(): string | null {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone ?? null
  } catch {
    return null
  }
}

/**
 * Radians exactly like SH3D: degrees pass through a Java float cast, then
 * Math.toRadians (deg / 180 * PI), then another float cast for storage.
 */
function toRadiansAsJavaFloat(degrees: number): number {
  return Math.fround((Math.fround(degrees) / 180) * Math.PI)
}

export function compassRadiansForZone(zoneId: string | null | undefined): {
  latitudeRad: number
  longitudeRad: number
} {
  const [latDeg, lonDeg] = compassDegreesForZone(zoneId ?? COMPASS_FALLBACK_ZONE)
  return {
    latitudeRad: toRadiansAsJavaFloat(latDeg),
    longitudeRad: toRadiansAsJavaFloat(lonDeg),
  }
}
